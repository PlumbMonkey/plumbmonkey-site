  "use strict";
  const ROWS = 15;

  function chunkRows(text, where) {
    const rows = text.split("\n").filter(r => r.length);
    const w = rows[0].length;
    rows.forEach((r, i) => { if (r.length !== w) throw new Error(`${where}: row ${i} is ${r.length} wide, expected ${w}`); });
    return rows;
  }
  function room(chunks, where) {
    let rows = null;
    chunks.forEach((c, k) => {
      const part = chunkRows(c, `${where} chunk ${k}`);
      if (!rows) rows = part.slice();
      else {
        if (part.length !== rows.length) throw new Error(`${where} chunk ${k}: ${part.length} rows, expected ${rows.length}`);
        rows = rows.map((r, i) => r + part[i]);
      }
    });
    return { w: rows[0].length, h: rows.length, rows };
  }
  function build(def) {
    const rooms = {};
    for (const name in def.rooms) rooms[name] = room(def.rooms[name], `${def.id} ${name}`);
    return Object.assign({}, def, { rooms });
  }

