/* Graveyard Shift — LEVEL DATA (no rules, no drawing).

   Each level is one or more ROOMS of 48px tiles. A room is authored as
   CHUNKS: blocks of equal-width ASCII rows joined left to right, so a section
   can be edited without recounting the whole row. build() rejects a chunk
   whose rows are ragged, so a miscounted line fails loudly at load time.

   LEGEND
     .  empty            #  ground            B  stone block
     G  ghost block — solid while formed; a note or a head-bump blasts it to
        vapour and it slowly re-forms
     L  echo block (Other Side only) — solid exactly while the ghost block in
        the same cell of the linked room is vapour
     ?  music box (Amp when small, Guitar after)   !  Encore box   $  soul-note box
     *  refilling music box — gives the next power tier and comes back, so a
        puzzle or a boss that needs the Guitar can never become unwinnable
     o  soul note        -  one-way ledge     =  crumbling floor    ^  spikes
     C  checkpoint lantern   E  great lantern — the level exit; it stands on the
        ground below the E, and touching anywhere in that column lights it
     D  door — the exit once the boss is down    X  boss spawn
     @  start            1-9 link endpoints (graves, portals, dumbwaiters)
   ENEMIES / MOVERS
     s skull crawler   k armoured Frankenstein   p cursed urn flower (urn tile)
     w potion witch    c cloud ghost   b bat   t gargoyle (drops from above)
     f fire bar pivot  F long fire bar   m swinging chandeliers
     h platform moving sideways   v platform moving up and down

   LINKS: every digit appears once in each of two rooms. `links[n]` gives the
   kind and, for one-way exits (a bonus crypt's way out), the only room it can
   be used FROM.

   Levels run WORLD_1, WORLD_2, ..., then FINALE. The Music Room is always the
   last level: add a new world as WORLD_3 and list it before FINALE in LEVELS. */
